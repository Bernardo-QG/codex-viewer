-- Secciones: árbol de categorías (Desarrollo › Backend › Spring Boot)
CREATE TABLE categories (
    id bigint generated by default as identity primary key,
    parent_id bigint references categories (id) on delete restrict,
    name text not null,
    slug text unique not null,
    description text,
    sort_order integer not null default 0,
    created_at timestamp with time zone not null default timezone('utc'::text, now()),
    constraint categories_slug_formato check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    constraint categories_sin_autorreferencia check (parent_id <> id),
    constraint categories_nombre_unico_por_padre unique nulls not distinct (parent_id, name)
);

CREATE INDEX idx_categories_padre ON categories (parent_id, sort_order);

-- Documentos
CREATE TABLE documents (
    id bigint generated by default as identity primary key,
    title text not null,
    slug text unique not null,
    summary text,
    content text not null,
    status text not null default 'published',
    category_id bigint references categories (id) on delete set null,
    sort_order integer not null default 0,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    updated_at timestamp with time zone not null default timezone('utc'::text, now()),
    constraint slug_formato check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    constraint documents_status_valido check (status in ('draft', 'published')),
    constraint documents_summary_largo check (char_length(summary) <= 300)
);

CREATE INDEX idx_documents_orden ON documents (category_id, sort_order);
CREATE INDEX idx_documents_status ON documents (status);

-- Etiquetas: temas que cruzan secciones (git, sql, angular)
CREATE TABLE tags (
    id bigint generated by default as identity primary key,
    name text not null,
    slug text unique not null,
    created_at timestamp with time zone not null default timezone('utc'::text, now()),
    constraint tags_slug_formato check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$')
);

-- Relación muchos a muchos entre documentos y etiquetas
CREATE TABLE document_tags (
    document_id bigint not null references documents (id) on delete cascade,
    tag_id bigint not null references tags (id) on delete cascade,
    primary key (document_id, tag_id)
);

CREATE INDEX idx_document_tags_tag ON document_tags (tag_id);

-- =========================================================
-- Trigger para mantener updated_at
-- =========================================================
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_documents_updated_at
    BEFORE UPDATE ON documents
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

