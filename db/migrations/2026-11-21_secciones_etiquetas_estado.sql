-- Migración: secciones anidadas, etiquetas, estado y resumen
-- Fecha: 2026-11-21
--
-- Parte del esquema que ya tiene las tablas categories y documents.
-- No borra datos: los documentos existentes quedan publicados.
-- Es idempotente: se puede ejecutar más de una vez sin error.
-- Ejecútala completa en el SQL Editor de Supabase.
-- =========================================================

BEGIN;

-- ---------- categories: árbol de secciones ----------
ALTER TABLE categories ADD COLUMN IF NOT EXISTS parent_id bigint REFERENCES categories (id) ON DELETE RESTRICT;
ALTER TABLE categories ADD COLUMN IF NOT EXISTS description text;

-- El nombre deja de ser único global; ahora es único dentro de la misma sección padre
ALTER TABLE categories DROP CONSTRAINT IF EXISTS categories_name_key;

DO $$
BEGIN
    ALTER TABLE categories ADD CONSTRAINT categories_nombre_unico_por_padre UNIQUE NULLS NOT DISTINCT (parent_id, name);
EXCEPTION WHEN duplicate_object OR duplicate_table THEN NULL;
END $$;

DO $$
BEGIN
    ALTER TABLE categories ADD CONSTRAINT categories_sin_autorreferencia CHECK (parent_id <> id);
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$
BEGIN
    ALTER TABLE categories ADD CONSTRAINT categories_slug_formato CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$');
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

CREATE INDEX IF NOT EXISTS idx_categories_padre ON categories (parent_id, sort_order);

-- ---------- documents: resumen y estado ----------
ALTER TABLE documents ADD COLUMN IF NOT EXISTS summary text;
ALTER TABLE documents ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'published';

DO $$
BEGIN
    ALTER TABLE documents ADD CONSTRAINT documents_status_valido CHECK (status IN ('draft', 'published'));
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

DO $$
BEGIN
    ALTER TABLE documents ADD CONSTRAINT documents_summary_largo CHECK (char_length(summary) <= 300);
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

CREATE INDEX IF NOT EXISTS idx_documents_status ON documents (status);

-- ---------- etiquetas ----------
CREATE TABLE IF NOT EXISTS tags (
    id bigint generated by default as identity primary key,
    name text not null,
    slug text unique not null,
    created_at timestamp with time zone not null default timezone('utc'::text, now()),
    constraint tags_slug_formato check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$')
);

CREATE TABLE IF NOT EXISTS document_tags (
    document_id bigint not null references documents (id) on delete cascade,
    tag_id bigint not null references tags (id) on delete cascade,
    primary key (document_id, tag_id)
);

CREATE INDEX IF NOT EXISTS idx_document_tags_tag ON document_tags (tag_id);

COMMIT;

